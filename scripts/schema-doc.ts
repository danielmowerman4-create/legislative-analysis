import { writeFileSync } from "node:fs";
import { sql } from "drizzle-orm";
import { runMigrations } from "../src/server/db/migrate";
import { closeDb, systemDb } from "../src/server/db/client";

const GROUPS: [string, string[]][] = [
  ["Organizations and users", ["organizations", "users", "sessions", "memberships", "roles", "permissions", "role_permissions", "invitations", "office_settings"]],
  ["Email", ["email_connections", "email_sync_state", "email_threads", "email_messages", "email_participants", "email_attachments", "email_drafts", "reply_deliveries", "message_notes", "message_events", "webhook_deliveries"]],
  ["Constituents", ["contacts", "contact_emails", "contact_addresses", "contact_merge_history", "contact_notes", "contact_communication_preferences"]],
  ["Classification", ["issue_taxonomy", "message_issue_links", "message_bill_links", "issue_positions", "classification_runs", "classification_feedback", "review_queue", "template_clusters"]],
  ["Legislation (public data, shared)", ["jurisdictions", "legislative_sessions", "bills", "bill_versions", "bill_actions", "bill_status_history", "bill_sponsors", "legislators", "committees", "bill_committee_links", "amendments", "roll_calls", "roll_call_votes", "legislative_events", "legislative_source_syncs"]],
  ["Legislation (office-owned)", ["tracked_bills", "follows", "bill_notes"]],
  ["Office operations", ["cases", "case_events", "case_assignments", "case_messages", "case_counters", "tasks", "task_events", "agency_directory"]],
  ["Communications", ["communication_drafts", "communication_draft_versions", "communication_approvals", "communication_batches", "communication_batch_recipients", "communication_delivery_logs"]],
  ["Constituent Center", ["mail_ledger", "mail_reconciliations", "sender_rules", "message_asks"]],
  ["Platform operations", ["notifications", "saved_views", "audit_logs", "security_events", "background_jobs", "integration_errors", "system_health_events", "oauth_states", "rate_limits", "assistant_queries"]],
];

async function main() {
  process.env.DATABASE_URL = "pglite://memory";
  await runMigrations();
  const db = await systemDb();
  type Col = {
    table_name: string; column_name: string; data_type: string; udt_name: string; is_nullable: string; column_default: string | null; is_generated: string;
  };
  const cols = (await db.execute<Col>(sql`
    select table_name, column_name, data_type, udt_name, is_nullable, column_default, is_generated
    from information_schema.columns where table_schema = 'public' order by table_name, ordinal_position`)).rows;
  const indexes = sql`select tablename, indexname, indexdef from pg_indexes where schemaname = 'public' order by tablename, indexname`;
  const idx = (await db.execute<{ tablename: string; indexname: string; indexdef: string }>(indexes)).rows;
  const fks = (await db.execute<{ table_name: string; column_name: string; foreign_table: string; delete_rule: string }>(sql`
    select tc.table_name, kcu.column_name, ccu.table_name as foreign_table, rc.delete_rule
    from information_schema.table_constraints tc
    join information_schema.key_column_usage kcu on kcu.constraint_name = tc.constraint_name
    join information_schema.constraint_column_usage ccu on ccu.constraint_name = tc.constraint_name
    join information_schema.referential_constraints rc on rc.constraint_name = tc.constraint_name
    where tc.constraint_type = 'FOREIGN KEY' and tc.table_schema = 'public'`)).rows;
  const secured = await db.execute<{ relname: string }>(sql`select relname from pg_class where relrowsecurity and relkind = 'r'`);
  const rls = new Set(secured.rows.map((r) => r.relname));
  const policies = (await db.execute<{ tablename: string; qual: string }>(sql`select tablename, qual from pg_policies where schemaname = 'public'`)).rows;
  const policyRow = (t: string) => {
    const qual = policies.find((p) => p.tablename === t)!.qual.replace(/\|/g, "\\|").replace(/\s+/g, " ");
    return `| ${t} | ${rls.has(t) ? "on" : "off"} | ${qual} |`;
  };

  const out: string[] = [
    "# Database schema",
    "",
    "Generated by `npm run schema:doc` from the migrated database (drizzle/*.sql). Do not edit by hand.",
    "",
    "## Tenant isolation",
    "",
    "Every table with an `organization_id` column has row-level security enabled with a `tenant_isolation` policy (`organization_id = app_org_id()`), applied to the `li_app` role that all office requests run as. `contact_notes` and `case_events` also restrict private rows to their author. Legislative data tables are global and read-only for `li_app`; `users` exposes only display columns to `li_app`.",
    "",
    "| Table | RLS | Policy |",
    "|---|---|---|",
    ...policies.filter((p) => !["contact_notes", "case_events"].includes(p.tablename)).length
      ? [...new Set(policies.map((p) => p.tablename))].sort().map(policyRow)
      : [],
    "",
  ];
  const typeOf = (c: Col) => {
    if (c.data_type === "ARRAY") return `${c.udt_name.replace(/^_/, "")}[]`;
    return c.data_type === "USER-DEFINED" ? c.udt_name : c.data_type.replace("timestamp with time zone", "timestamptz");
  };
  const indexLabel = (i: (typeof idx)[number]) => {
    const kind = /USING (gin|hnsw)/.exec(i.indexdef)?.[1];
    return `\`${i.indexname}\`${/UNIQUE/.test(i.indexdef) ? " (unique)" : ""}${kind ? ` (${kind})` : ""}`;
  };
  for (const [group, tables] of GROUPS) {
    out.push(`## ${group}`, "");
    for (const t of tables) {
      const tc = cols.filter((c) => c.table_name === t);
      if (!tc.length) continue;
      out.push(`### ${t}${rls.has(t) ? " (RLS)" : ""}`, "", "| Column | Type | Null | Default / notes |", "|---|---|---|---|");
      for (const c of tc) {
        const fk = fks.find((f) => f.table_name === t && f.column_name === c.column_name);
        const fkNote = fk ? `→ ${fk.foreign_table} (on delete ${fk.delete_rule.toLowerCase()})` : null;
        const notes = [c.is_generated === "ALWAYS" ? "generated" : c.column_default?.replace(/::[a-z ]+/g, "").slice(0, 40), fkNote].filter(Boolean).join("; ");
        out.push(`| ${c.column_name} | ${typeOf(c)} | ${c.is_nullable === "YES" ? "yes" : ""} | ${notes.replace(/\|/g, "\\|")} |`);
      }
      const ti = idx.filter((i) => i.tablename === t && !i.indexname.endsWith("_pkey"));
      if (ti.length) out.push("", `Indexes: ${ti.map(indexLabel).join(", ")}`);
      out.push("");
    }
  }
  const listed = new Set(GROUPS.flatMap(([, t]) => t));
  const missing = [...new Set(cols.map((c) => c.table_name))].filter((t) => !listed.has(t) && !t.startsWith("__"));
  if (missing.length) out.push(`## Other`, "", missing.map((m) => `- ${m}`).join("\n"), "");
  writeFileSync("DATABASE_SCHEMA.md", out.join("\n"));
  console.log(`Wrote DATABASE_SCHEMA.md (${new Set(cols.map((c) => c.table_name)).size} tables)`);
}

main().finally(() => closeDb());
